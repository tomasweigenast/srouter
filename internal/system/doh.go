// DoHConfig is the persisted user configuration (single row in doh_config).
type DoHConfig struct {
	Enabled          bool
	ProviderID       string // builtin provider ID or "custom"
	FallbackToPlain  bool
	StashedUpstreams string // comma-separated; internal use only
	CustomDoTIP      string // used when ProviderID == "custom"
	CustomDoTTLSName string
	CustomDoHURL     string // HTTPS DoH URL, e.g. https://dns.quad9.net/dns-query
}

// DoHStatus is the runtime state returned to the UI.
type DoHStatus struct {
	DoTInstalled bool
	DoHInstalled bool
	DoTRunning   bool
	DoHRunning   bool
	Config       DoHConfig
	Providers    []DoHProvider
}

// AnyInstalled reports whether at least one encrypted DNS tool is present.
func (s DoHStatus) AnyInstalled() bool { return s.DoTInstalled || s.DoHInstalled }

